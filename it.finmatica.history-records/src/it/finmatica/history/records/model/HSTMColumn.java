package it.finmatica.history.records.model;

import org.compiere.model.X_AD_Column;

public class HSTMColumn {

	public static final String COLUMNNAME_HST_IsHstColumn = "HST_IsHstColumn";

	public static boolean isHST_IsHstColumn(X_AD_Column c) {
		Object oo = c.get_Value(COLUMNNAME_HST_IsHstColumn);
		if (oo != null) {
			if (oo instanceof Boolean)
				return ((Boolean) oo).booleanValue();
			return "Y".equals(oo);
		}
		return false;
	}

	public static void setHST_IsHstColumn(X_AD_Column c, boolean HST_IsHstColumn) {
		c.set_ValueOfColumn(COLUMNNAME_HST_IsHstColumn, Boolean.valueOf(HST_IsHstColumn));
	}
}
